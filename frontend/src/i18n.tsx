const originalText = new WeakMap<Text, { original: string; rendered: string }>()
const originalAttributes = new WeakMap<Element, Record<string, { original: string; rendered: string }>>()

function translateCore(value: string): string {
  const exact = translations[value]
  if (typeof exact === 'string') return exact
  for (const [pattern, replacement] of patterns) {
    const match = value.match(pattern)
    if (match) return replacement(match)
  }
  return value
}

function translateText(value: string): string {
  const core = value.trim()
  if (!core) return value
  const translated = translateCore(core)
  if (translated === core) return value
  const leading = value.slice(0, value.indexOf(core))
  const trailing = value.slice(value.indexOf(core) + core.length)
  return `${leading}${translated}${trailing}`
}

export function UiTranslator() {
  const language = useLanguage()

  useEffect(() => {
    if (typeof document === 'undefined') return
    document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN'
    let applying = false

    const apply = () => {
      applying = true
      const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT)
      let node: Node | null
      while ((node = walker.nextNode())) {
        const text = node as Text
        if (!text.parentElement || ['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(text.parentElement.tagName)) continue
        const previous = originalText.get(text)
        const original = previous && text.data === previous.rendered ? previous.original : text.data
        const translated = language === 'en' ? translateText(original) : original
        originalText.set(text, { original, rendered: translated })
        if (text.data !== translated) text.data = translated
      }
      document.querySelectorAll('[aria-label],[placeholder],[title]').forEach((element) => {
        const saved = originalAttributes.get(element) ?? {}
        for (const attribute of ['aria-label', 'placeholder', 'title']) {
          const value = element.getAttribute(attribute)
          const previous = saved[attribute]
          const original = previous && value === previous.rendered ? previous.original : value
          if (original) {
            const translated = language === 'en' ? translateText(original) : original
            saved[attribute] = { original, rendered: translated }
            element.setAttribute(attribute, translated)
          }
        }
        originalAttributes.set(element, saved)
      })
      applying = false
    }

    apply()
    const observer = new MutationObserver(() => {
      if (!applying) apply()
    })
    observer.observe(document.body, { childList: true, characterData: true, subtree: true })
    return () => observer.disconnect()
  }, [language])

  return null
}
